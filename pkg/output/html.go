// writeHTMLSortScript writes the minimal inline JavaScript for column sorting.
func writeHTMLSortScript(sb *strings.Builder) {
	sb.WriteString(`<script>
(function(){
  var table = document.getElementById('findings-table');
  if(!table) return;
  var thead = table.querySelector('thead th');
  var tbody = table.querySelector('tbody');
  var headers = table.querySelectorAll('thead th');
  var sortDir = 1;
  var sortCol = -1;

  headers.forEach(function(th, idx){
    th.addEventListener('click', function(){
      if(sortCol === idx){ sortDir = -sortDir; }
      else { sortCol = idx; sortDir = 1; }
      headers.forEach(function(h){ h.classList.remove('sorted-asc','sorted-desc'); });
      th.classList.add(sortDir === 1 ? 'sorted-asc' : 'sorted-desc');

      var rows = Array.prototype.slice.call(tbody.querySelectorAll('tr'));
      var dataType = th.getAttribute('data-type') || 'string';
      rows.sort(function(a, b){
        var va = a.children[idx].textContent.trim();
        var vb = b.children[idx].textContent.trim();
        if(dataType === 'number'){
          va = parseFloat(va) || 0; vb = parseFloat(vb) || 0;
        }
        if(va < vb) return -sortDir;
        if(va > vb) return sortDir;
        return 0;
      });
      rows.forEach(function(r){ tbody.appendChild(r); });
    });
  });
})();
</script>
`)
}
