// writeHTMLFindingsTable writes the sortable findings table.
func writeHTMLFindingsTable(sb *strings.Builder, result *scanner.ScanResult) {
	sb.WriteString("  <p class=\"section-title\">Findings</p>\n")

	if len(result.Findings) == 0 {
		sb.WriteString("  <div class=\"no-findings\">\n")
		sb.WriteString("    <p>✅ No security findings detected. Scan passed.</p>\n")
		sb.WriteString("  </div>\n")
		sb.WriteString("</div>\n")
		return
	}

	sorted := sortFindings(result.Findings)

	sb.WriteString("  <table id=\"findings-table\">\n")
	sb.WriteString("    <thead>\n")
	sb.WriteString("      <tr>\n")
	sb.WriteString("        <th data-type=\"string\">Severity</th>\n")
	sb.WriteString("        <th data-type=\"string\">File</th>\n")
	sb.WriteString("        <th data-type=\"number\">Line</th>\n")
	sb.WriteString("        <th data-type=\"string\">Rule</th>\n")
	sb.WriteString("        <th data-type=\"string\">Category</th>\n")
	sb.WriteString("        <th data-type=\"string\">Message</th>\n")
	sb.WriteString("        <th data-type=\"string\">Match</th>\n")
	sb.WriteString("        <th data-type=\"string\">CWE / OWASP</th>\n")
	sb.WriteString("      </tr>\n")
	sb.WriteString("    </thead>\n")
	sb.WriteString("    <tbody>\n")

	for _, f := range sorted {
		writeHTMLFindingRow(sb, f)
	}

	sb.WriteString("    </tbody>\n")
	sb.WriteString("  </table>\n")
	sb.WriteString("</div>\n")
}

// writeHTMLFindingRow writes a single table row for a finding.
func writeHTMLFindingRow(sb *strings.Builder, f scanner.Finding) {
	meta := GetRuleMetadataWithDefault(f.RuleID)

	// CWE list.
	cwes := make([]string, len(meta.CWE))
	for i, c := range meta.CWE {
		cwes[i] = fmt.Sprintf("CWE-%d", c)
	}
	cweStr := strings.Join(cwes, ", ")

	owaspStr := meta.OWASPLLMTop
	if owaspStr != "" && meta.OWASPName != "" {
		owaspStr = fmt.Sprintf("%s (%s)", meta.OWASPLLMTop, meta.OWASPName)
	}

	metaParts := []string{}
	if cweStr != "" {
		metaParts = append(metaParts, cweStr)
	}
	if owaspStr != "" {
		metaParts = append(metaParts, owaspStr)
	}
	metaStr := strings.Join(metaParts, "<br>")

	sb.WriteString("    <tr>\n")
	sb.WriteString(fmt.Sprintf("      <td><span class=\"badge %s\">%s</span></td>\n",
		html.EscapeString(string(f.Severity)), html.EscapeString(string(f.Severity))))
	sb.WriteString(fmt.Sprintf("      <td class=\"mono\">%s</td>\n",
		html.EscapeString(f.Artifact)))
	sb.WriteString(fmt.Sprintf("      <td>%d:%d</td>\n", f.Line, f.Column))
	sb.WriteString(fmt.Sprintf("      <td>%s</td>\n", html.EscapeString(f.RuleID)))
	sb.WriteString(fmt.Sprintf("      <td>%s</td>\n", html.EscapeString(f.Category)))
	sb.WriteString(fmt.Sprintf("      <td>%s</td>\n", html.EscapeString(f.Message)))
	sb.WriteString(fmt.Sprintf("      <td class=\"match mono\" title=\"%s\">%s</td>\n",
		html.EscapeString(f.MatchedText), html.EscapeString(f.MatchedText)))
	sb.WriteString(fmt.Sprintf("      <td class=\"meta\">%s</td>\n", metaStr))
	sb.WriteString("    </tr>\n")
}

