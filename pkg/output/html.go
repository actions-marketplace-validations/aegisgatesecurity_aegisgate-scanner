// FormatHTML produces a self-contained HTML report from scan results.
// The output includes inline CSS and minimal JavaScript for sortable
// table columns. No external resources are referenced.
func FormatHTML(result *scanner.ScanResult, root, toolVersion string) ([]byte, error) {
	if result == nil {
		result = &scanner.ScanResult{
			Findings: []scanner.Finding{},
			Stats: scanner.ScanStats{
				BySeverity: make(map[detectors.Severity]int),
				ByCategory: make(map[string]int),
				ByLayer:    make(map[string]int),
			},
		}
	}
	if result.Findings == nil {
		result.Findings = []scanner.Finding{}
	}
	if result.Stats.BySeverity == nil {
		result.Stats.BySeverity = make(map[detectors.Severity]int)
	}
	if result.Stats.ByCategory == nil {
		result.Stats.ByCategory = make(map[string]int)
	}
	if result.Stats.ByLayer == nil {
		result.Stats.ByLayer = make(map[string]int)
	}

	var sb strings.Builder

	sb.WriteString("<!DOCTYPE html>\n")
	sb.WriteString("<html lang=\"en\">\n")
	sb.WriteString("<head>\n")
	sb.WriteString("<meta charset=\"UTF-8\">\n")
	sb.WriteString(fmt.Sprintf("<title>AegisGate Scanner Report — %s</title>\n", html.EscapeString(root)))
	sb.WriteString("<style>\n")
	writeHTMLStyles(&sb)
	sb.WriteString("</style>\n")
	sb.WriteString("</head>\n")
	sb.WriteString("<body>\n")

	// Header.
	sb.WriteString("<div class=\"header\">\n")
	sb.WriteString("  <h1>🛡️ AegisGate Scanner Report</h1>\n")
	sb.WriteString(fmt.Sprintf("  <p class=\"version\">Version %s</p>\n", html.EscapeString(toolVersion)))
	sb.WriteString("</div>\n")

	// Summary section.
	writeHTMLSummary(&sb, result, root)

	// Findings table.
	writeHTMLFindingsTable(&sb, result)

	// Footer.
	sb.WriteString("<div class=\"footer\">\n")
	sb.WriteString("  <p>Generated by <a href=\"https://aegisgatesecurity.io\">AegisGate Scanner</a></p>\n")
	sb.WriteString("</div>\n")

	// Sorting script.
	writeHTMLSortScript(&sb)

	sb.WriteString("</body>\n")
	sb.WriteString("</html>\n")

	return []byte(sb.String()), nil
}

