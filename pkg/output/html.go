// writeHTMLSummary writes the summary cards and category breakdown.
func writeHTMLSummary(sb *strings.Builder, result *scanner.ScanResult, root string) {
	sb.WriteString("<div class=\"container\">\n")

	// Scan info.
	sb.WriteString(fmt.Sprintf("  <p class=\"muted\">Scan root: <code>%s</code> | Duration: %s</p>\n",
		html.EscapeString(root), result.Duration))

	// Stat cards.
	sb.WriteString("  <div class=\"summary\">\n")
	writeHTMLStatCard(sb, "Files Scanned", result.Stats.FilesScanned, "")
	writeHTMLStatCard(sb, "Files With Findings", result.Stats.FilesWithFindings, "")
	writeHTMLStatCard(sb, "Total Findings", result.Stats.TotalFindings, "")
	writeHTMLStatCard(sb, "Critical", result.Stats.BySeverity[detectors.SeverityCritical], "critical")
	writeHTMLStatCard(sb, "High", result.Stats.BySeverity[detectors.SeverityHigh], "high")
	writeHTMLStatCard(sb, "Medium", result.Stats.BySeverity[detectors.SeverityMedium], "medium")
	writeHTMLStatCard(sb, "Low", result.Stats.BySeverity[detectors.SeverityLow], "low")
	sb.WriteString("  </div>\n")

	// Category breakdown.
	if len(result.Stats.ByCategory) > 0 {
		sb.WriteString("  <p class=\"section-title\">By Category</p>\n")
		sb.WriteString("  <div class=\"category-list\">\n")
		cats := make([]string, 0, len(result.Stats.ByCategory))
		for cat := range result.Stats.ByCategory {
			cats = append(cats, cat)
		}
		sort.Strings(cats)
		for _, cat := range cats {
			sb.WriteString(fmt.Sprintf("    <span class=\"category-badge\">%s: %d</span>\n",
				html.EscapeString(cat), result.Stats.ByCategory[cat]))
		}
		sb.WriteString("  </div>\n")
	}
}

// writeHTMLStatCard writes a single stat card.
func writeHTMLStatCard(sb *strings.Builder, label string, value int, class string) {
	if class != "" {
		sb.WriteString(fmt.Sprintf("    <div class=\"card %s\"><div class=\"value\">%d</div><div class=\"label\">%s</div></div>\n",
			class, value, html.EscapeString(label)))
	} else {
		sb.WriteString(fmt.Sprintf("    <div class=\"card\"><div class=\"value\">%d</div><div class=\"label\">%s</div></div>\n",
			value, html.EscapeString(label)))
	}
}

